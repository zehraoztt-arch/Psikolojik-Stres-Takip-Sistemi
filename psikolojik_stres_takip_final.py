# Günlük stres kayıtlarını saklayan liste
kayitlar = []


# 1. STRES PUANI ALMA
def stres_puani_al():
    while True:
        try:
            stres = int(input("Stres seviyeniz (1-10): "))

            if 1 <= stres <= 10:
                return stres
            else:
                print("Hata! Stres seviyesi 1-10 arasında olmalıdır.")

        except ValueError:
            print("Hata! Lütfen geçerli bir tam sayı giriniz.")


# 2. UYKU SÜRESİ ALMA
def uyku_suresi_al():
    while True:
        try:
            uyku = float(input(
                "Dün gece kaç saat uyudunuz? (0-24): "
            ).replace(",", "."))

            if 0 <= uyku <= 24:
                return uyku
            else:
                print("Hata! Uyku süresi 0-24 arasında olmalıdır.")

        except ValueError:
            print("Hata! Lütfen geçerli bir sayı giriniz.")


# 3. RUH HALİ ALMA
def ruh_hali_al():
    while True:
        ruh_hali = input(
            "Ruh haliniz (İyi/Orta/Kötü): "
        ).strip().replace("İ", "i").replace("I", "ı").lower()

        if ruh_hali in ["iyi", "orta", "kötü", "kotu"]:
            if ruh_hali == "kotu":
                ruh_hali = "kötü"
            return ruh_hali

        print("Hata! Lütfen İyi, Orta veya Kötü giriniz.")


# 4. STRES KATEGORİSİ BELİRLEME
def stres_analiz_et(stres):
    if stres <= 3:
        return "Düşük"
    elif stres <= 6:
        return "Orta"
    else:
        return "Yüksek"


# 5. YENİ KAYIT EKLEME
def kayit_ekle():
    print("\n--- YENİ GÜNLÜK STRES KAYDI ---")

    stres = stres_puani_al()
    uyku = uyku_suresi_al()
    ruh_hali = ruh_hali_al()

    yeni_kayit = {
        "stres": stres,
        "uyku": uyku,
        "ruh_hali": ruh_hali,
        "kategori": stres_analiz_et(stres)
    }

    kayitlar.append(yeni_kayit)

    print("\nKayıt başarıyla eklendi!")
    print("Stres Kategorisi:", yeni_kayit["kategori"])


# 6. KAYITLARI LİSTELEME
def kayitlari_listele():
    if len(kayitlar) == 0:
        print("\nHenüz kayıt bulunmamaktadır.")
        return

    print("\n===== GÜNLÜK STRES KAYITLARI =====")

    for sira, kayit in enumerate(kayitlar, start=1):
        print("\nKayıt No:", sira)
        print("Stres Seviyesi:", kayit["stres"])
        print("Uyku Süresi:", kayit["uyku"], "saat")
        print("Ruh Hali:", kayit["ruh_hali"].capitalize())
        print("Stres Kategorisi:", kayit["kategori"])


# 7. GENEL ANALİZ
def genel_analiz():
    if len(kayitlar) == 0:
        print("\nAnaliz için kayıt bulunmuyor.")
        return

    ortalama_stres = sum(
        k["stres"] for k in kayitlar
    ) / len(kayitlar)

    ortalama_uyku = sum(
        k["uyku"] for k in kayitlar
    ) / len(kayitlar)

    dusuk = sum(
        1 for k in kayitlar if k["kategori"] == "Düşük"
    )
    orta = sum(
        1 for k in kayitlar if k["kategori"] == "Orta"
    )
    yuksek = sum(
        1 for k in kayitlar if k["kategori"] == "Yüksek"
    )

    print("\n===== GENEL STRES ANALİZ RAPORU =====")
    print("Toplam Kayıt Sayısı:", len(kayitlar))
    print("Ortalama Stres Seviyesi:", round(ortalama_stres, 2))
    print("Ortalama Uyku Süresi:", round(ortalama_uyku, 2), "saat")

    print("\n--- STRES DAĞILIMI ---")
    print("Düşük Stres:", dusuk, "kayıt")
    print("Orta Stres:", orta, "kayıt")
    print("Yüksek Stres:", yuksek, "kayıt")


# 8. RAPORU TXT DOSYASINA KAYDETME
def rapor_kaydet():
    if len(kayitlar) == 0:
        print("\nKaydedilecek kayıt bulunmamaktadır.")
        return

    ortalama_stres = sum(
        k["stres"] for k in kayitlar
    ) / len(kayitlar)

    ortalama_uyku = sum(
        k["uyku"] for k in kayitlar
    ) / len(kayitlar)

    with open("stres_raporu.txt", "w", encoding="utf-8") as dosya:
        dosya.write("PSİKOLOJİK STRES TAKİP VE ANALİZ RAPORU\n")
        dosya.write("=====================================\n\n")

        dosya.write(f"Toplam Kayıt: {len(kayitlar)}\n")
        dosya.write(f"Ortalama Stres: {ortalama_stres:.2f}\n")
        dosya.write(f"Ortalama Uyku: {ortalama_uyku:.2f} saat\n\n")

        dosya.write("STRES DAĞILIMI\n")
        for kategori in ["Düşük", "Orta", "Yüksek"]:
            sayi = sum(
                1 for k in kayitlar if k["kategori"] == kategori
            )
            dosya.write(f"{kategori} Stres: {sayi} kayıt\n")

        dosya.write("\nGÜNLÜK KAYITLAR\n")

        for sira, kayit in enumerate(kayitlar, start=1):
            dosya.write(f"\nKayıt {sira}\n")
            dosya.write(f"Stres: {kayit['stres']}\n")
            dosya.write(f"Uyku: {kayit['uyku']} saat\n")
            dosya.write(f"Ruh Hali: {kayit['ruh_hali']}\n")
            dosya.write(f"Kategori: {kayit['kategori']}\n")

        dosya.write("\nBu rapor psikolojik tanı amacı taşımaz.\n")

    print("\nRapor başarıyla stres_raporu.txt dosyasına kaydedildi!")


# 9. ANA MENÜ
def ana_menu():
    while True:
        print("\n========================================")
        print(" PSİKOLOJİK STRES TAKİP SİSTEMİ")
        print("========================================")

        print("1 - Yeni Stres Kaydı Ekle")
        print("2 - Günlük Kayıtları Listele")
        print("3 - Genel Stres Analizi Yap")
        print("4 - Stres Raporunu Dosyaya Kaydet")
        print("5 - Programdan Çık")

        secim = input("\nSeçiminiz (1-5): ").strip()

        if secim == "1":
            kayit_ekle()
        elif secim == "2":
            kayitlari_listele()
        elif secim == "3":
            genel_analiz()
        elif secim == "4":
            rapor_kaydet()
        elif secim == "5":
            print("\nProgramdan çıkılıyor...")
            print("Teşekkür ederiz!")
            break
        else:
            print("\nHatalı seçim! Lütfen 1-5 arasında bir sayı giriniz.")


# 10. PROGRAMI BAŞLAT
if __name__ == "__main__":
    print("2030 - Psikolojik Stres Takip ve Analiz Sistemi")
    print("Bu uygulama psikolojik tanı koymaz.")
    ana_menu()